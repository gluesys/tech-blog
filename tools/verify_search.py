#!/usr/bin/env python3
"""Run the acceptance queries against the built Pagefind index (stdlib only).

    python3 tools/verify_search.py --build build --cases tools/search_cases.txt \
        [--out migration/search-results.md]

Each line of the cases file is `query<TAB>expected url path`. A case passes when
the expected path is among the top 5 results. The queries run through `node`
of tools/verify_search.ts, which imports build/pagefind/pagefind.js and the same
variant-merging code the site UI uses. The tool reports only: it exits 0 even
when cases fail (spec 9.1); failures go to the site owner.
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOP_N = 5


def parse_cases(text):
    cases = []
    for n, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        parts = line.rstrip("\n").split("\t")
        if len(parts) != 2 or not parts[0].strip() or not parts[1].startswith("/"):
            raise ValueError(f"line {n}: expected `query<TAB>/expected/path`")
        cases.append((parts[0].strip(), parts[1].strip()))
    return cases


def judge(expected, top):
    return "PASS" if expected in top[:TOP_N] else "FAIL"


def render_table(rows):
    """rows: dicts with query, variants, expected, top, status."""
    out = ["| Query | Variants run | Expected | Top 5 | Result |", "|---|---|---|---|---|"]
    for r in rows:
        variants = " , ".join(f"`{v}`" for v in r["variants"])
        top = "<br>".join(f"{i}. `{p}`" for i, p in enumerate(r["top"][:TOP_N], 1)) or "(none)"
        out.append(f"| `{r['query']}` | {variants} | `{r['expected']}` | {top} | {r['status']} |")
    return "\n".join(out)


def run_queries(build, queries):
    cmd = ["node", str(ROOT / "tools" / "verify_search.ts"), str(build), *queries]
    proc = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise RuntimeError(proc.stderr.strip() or f"node exited {proc.returncode}")
    return {d["query"]: d for d in map(json.loads, proc.stdout.splitlines())}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--build", default="build")
    ap.add_argument("--cases", default=str(ROOT / "tools" / "search_cases.txt"))
    ap.add_argument("--out", help="also write the results table to this Markdown file")
    args = ap.parse_args(argv)

    if not (Path(args.build) / "pagefind" / "pagefind.js").is_file():
        print(f"no Pagefind index under {args.build}/pagefind (run pagefind --site {args.build})")
        return 0
    cases = parse_cases(Path(args.cases).read_text(encoding="utf-8"))
    try:
        found = run_queries(args.build, [q for q, _ in cases])
    except (RuntimeError, OSError, ValueError) as e:
        print(f"search check could not run: {e}")
        return 0
    rows = []
    for q, expected in cases:
        d = found.get(q, {"variants": [q], "top": []})
        rows.append({"query": q, "variants": d["variants"], "expected": expected,
                     "top": d["top"], "status": judge(expected, d["top"])})
    for r in rows:
        print(f"{r['status']}  {r['query']}  -> {r['expected']}")
    passed = sum(r["status"] == "PASS" for r in rows)
    print(f"search acceptance: {passed}/{len(rows)} pass")
    if args.out:
        body = ("# Search acceptance results\n\n"
                f"Generated by `tools/verify_search.py` against the built Pagefind index. "
                f"PASS means the expected path is in the top {TOP_N}. "
                f"Result: **{passed}/{len(rows)}**.\n\n" + render_table(rows) + "\n")
        Path(args.out).write_text(body, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
